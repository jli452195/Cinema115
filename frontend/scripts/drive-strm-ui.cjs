    assert.equal(await events.inputValue(), '0', 'failed save must retain the disabled event schedule')
    assert.equal(await reconcile.inputValue(), '0', 'failed save must retain the disabled reconcile schedule')
    assert.equal(await fullScan.inputValue(), '0', 'failed save must retain the disabled full scan schedule')
    await basic.getByRole('button', { name: '保存设置', exact: true }).click()
