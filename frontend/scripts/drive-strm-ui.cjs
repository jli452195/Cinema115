    await basic.getByRole('button', { name: '还原修改', exact: true }).click()
    assert.equal(await videos.inputValue(), 'mkv,mp4')
    assert.equal(await events.inputValue(), '0', 'restore must recover the saved event schedule')
    assert.equal(await reconcile.inputValue(), '0')
    assert.equal(await fullScan.inputValue(), '0')
