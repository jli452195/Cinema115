    let editor = page.getByRole('dialog', { name: '新增目录', exact: true })
    assert.equal(await editor.getByRole('button', { name: '保存目录', exact: true }).isDisabled(), true)
    assert.equal(await editor.getByLabel('STRM 播放地址', { exact: true }).count(), 0)
    assert.equal(await editor.getByLabel('视频后缀', { exact: true }).count(), 0)
    assert.equal(await editor.getByRole('combobox').count(), 0, 'schedules belong to basic settings, not directory editors')
    assert.equal(await editor.getByText('附加文件', { exact: false }).count(), 0)
    await editor.getByRole('button', { name: /选择云端目录/ }).click()
    const directory = page.getByRole('dialog', { name: '选择主网盘来源目录', exact: true })
